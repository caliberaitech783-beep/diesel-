const pdf = Buffer.from('%PDF-1.4\n%%EOF');
const attachment = {name:'sample.pdf',base64:pdf.toString('base64')};
const maker = {id:'maker',name:'Master Maker',site:'Test site',canEditMasters:true};
const samples = {number:'100',date:'2026-11-21',time:'06:00',email:'test@example.com',file:attachment};
const sampleValues = slug => Object.fromEntries(masterDefinition(slug).fields.filter(field=>field.required && !field.readOnly)
  .map(field=>[field.key,field.options?.[0] ?? samples[field.type] ?? 'Sample']));

test('all 20 Diesel masters expose a dialog and owners can edit, reopen and delete private submissions',async t=>{
  const directory = await mkdtemp(join(tmpdir(),'diesel-editing-'));
  t.after(()=>rm(directory,{recursive:true,force:true}));
  let store = await openItemSubmissions(directory);
  for (const slug of recordMasters) {
    const master = masterDefinition(slug);
    const created = await store.create(maker,slug,sampleValues(slug));
    const values = {...created.values};
    if (slug === 'reason-code-master') values.Description = 'Updated description';
    const table = masterDataPage({actor:maker,master,rows:[{id:created.id,code:created.code,fields:Object.entries(values)}],canSave:true,local:true,offset:0,pageSize:50});
    assert.match(table,/data-record-dialog/);
    assert.match(table,/>Actions</);
    assert.match(table,/>Edit</,slug);
    const form = recordsPage({master,actor:maker,rows:[],record:created,editingAllowed:true,submissionsOnly:true,dialog:true});
    assert.match(form,/class="record-dialog-page"/);
    assert.match(form,/data-delete-record/);
    assert.match(form,/data-dialog-cancel/);
    assert.match(form,/Reason for deletion/);
    assert.doesNotMatch(form,/data-action="deactivate"/);
    await assert.rejects(store.update(maker,slug,created.id,{revision:0,reason:'Fix',values}),{status:409});
    await assert.rejects(store.update(maker,slug,created.id,{revision:1,reason:'',values}),{status:422});
    const updated = await store.update(maker,slug,created.id,{revision:1,reason:'Verified correction',values});
    assert.equal(updated.revision,2,slug);
    assert.equal(updated.id,created.id);
    if (slug === 'reason-code-master') assert.equal(updated.values.Description,'Updated description');
    const fileFields = master.fields.filter(field=>field.type === 'file' && updated.values[field.key]);
    for (const field of fileFields) assert.deepEqual((await store.attachment(maker,slug,updated.id,updated.values[field.key].id)).bytes,pdf);
    for (const field of fileFields) assert.deepEqual((await store.attachment(maker,slug,created.id,created.values[field.key].id)).bytes,pdf);
    store = await openItemSubmissions(directory);
    assert.equal((await store.get(maker,slug,created.id)).revision,2);
    await assert.rejects(store.delete({...maker,id:'outsider'},slug,created.id,{revision:2,reason:'Delete'}),{status:403});
    await store.delete(maker,slug,created.id,{revision:2,reason:'Duplicate record'});
    assert.deepEqual(await store.list(maker,slug,{search:'',offset:0}),[]);
    assert.equal((await store.get(maker,slug,created.id)).changes.at(-1).action,'deleted');
    await assert.rejects(store.update(maker,slug,created.id,{revision:3,reason:'Cannot resurrect',values}),{status:409});
  }
});

test('shared deletion requires another checker, keeps the approved revision until approval and retains history',async t=>{
  const db = openDieselDatabase(':memory:');
  t.after(()=>db.close());
  const actors = {maker,checker:{id:'checker',site:maker.site,canApproveMasters:true},viewer:{id:'viewer',site:maker.site},other:{...maker,site:'Other'}};
  const app = express();
  const store = registerMasterRecords(app,{db,getActor:req=>actors[req.get('test-actor')],enabledMasters:recordMasters});
  const server = app.listen(0,'127.0.0.1');
  await once(server,'listening');
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const origin = 'http://127.0.0.1:'+server.address().port;
  const call = (path,actor='maker',body,headers={})=>fetch(origin+path,{method:body ? 'POST' : 'GET',headers:{'test-actor':actor,'content-type':'application/json',...headers},body:body ? JSON.stringify(body) : undefined});
  const slug = 'reason-code-master';
  const record = store.create(slug,{site:maker.site,values:{...sampleValues(slug),Code:'R1'}},maker);
  const approved = store.changeStatus(slug,record.id,1,'approve',actors.checker);
  const endpoint = '/api/masters/'+slug+'/records/'+record.id;
  for (const actor of ['viewer','checker']) assert.equal((await call(endpoint+'/delete',actor,{revision:2,reason:'Duplicate'})).status,403);
  assert.equal((await call(endpoint+'/delete','other',{revision:2,reason:'Duplicate'})).status,404);
  assert.equal((await call(endpoint+'/delete','maker',{revision:2,reason:'Duplicate'},{origin:'https://foreign.test'})).status,403);
  assert.equal((await call(endpoint+'/delete','maker',{revision:1,reason:'Duplicate'})).status,409);
  const pending = await (await call(endpoint+'/delete','maker',{revision:2,reason:'Duplicate'})).json();
  assert.equal(pending.status,'pending_deletion');
  assert.equal(readActiveMasters(db,maker.site,[slug])[slug][0].revision,approved.revision);
  assert.equal((await call(endpoint+'/approve','maker',{revision:3})).status,403);
  assert.equal((await call(endpoint+'/approve','checker',{revision:3})).status,200);
  assert.deepEqual(store.list(slug),[]);
  assert.deepEqual(readActiveMasters(db,maker.site,[slug])[slug],[]);
  assert.equal(store.get(slug,record.id).status,'deleted');
  assert.equal(store.history(slug,record.id).find(event=>event.action==='delete').reason,'Duplicate');
  assert.equal(store.snapshot(slug,record.id,2).status,'approved');
  assert.throws(()=>store.update(slug,record.id,{revision:4,reason:'No',values:record.values},maker),{status:409});
  const page = await call('/records?master='+slug+'&id='+record.id+'&dialog=1');
  assert.match(page.headers.get('content-security-policy'),/frame-ancestors 'self'/);
  assert.doesNotMatch(await page.text(),/data-delete-record|data-save-for-review/);
});

test('deletion checks working and approved master dependencies',t=>{
  const db = openDieselDatabase(':memory:');
  t.after(()=>db.close());
  const store = createMasterStore(db,recordMasters);
  const account = store.createPrivateSubmission('account-master',sampleValues('account-master'),maker);
  const depotValues = {...sampleValues('supplier-depot-master'),'Supplier (A/C Code)':account.code};
  const depot = store.createPrivateSubmission('supplier-depot-master',depotValues,maker);
  store.changeStatus('supplier-depot-master',depot.id,1,'approve',{id:'checker'});
  const alternate = store.createPrivateSubmission('account-master',{...sampleValues('account-master'),'A/C Code':'Different'},maker);
  store.changeStatus('account-master',alternate.id,1,'approve',{id:'checker'});
  store.update('supplier-depot-master',depot.id,{revision:2,reason:'Remove supplier',values:{...depotValues,'Supplier (A/C Code)':alternate.code}},maker);
  assert.throws(()=>store.changeStatus('account-master',account.id,1,'delete',maker,'No longer needed'),/used by/);
});

test('private update and deletion reject other owners, changed sessions and cross-origin requests',async t=>{
  const directory = await mkdtemp(join(tmpdir(),'diesel-private-api-'));
  const store = await openItemSubmissions(directory);
  const app = express();
  registerItemSubmissions(app,{store,publicOrigin:'https://diesel.test',getProfile:req=>({login:req.get('test-actor') ?? 'maker'})});
  const server = app.listen(0,'127.0.0.1');
  await once(server,'listening');
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(directory,{recursive:true,force:true});});
  const origin='http://127.0.0.1:'+server.address().port;
  const slug='reason-code-master';
  const record=await store.create({id:'maker'},slug,sampleValues(slug));
  const endpoint='/api/masters/'+slug+'/records/'+record.id;
  const call=(path,method,actor='maker',extra={},requestOrigin='https://diesel.test')=>fetch(origin+path,{method,headers:{origin:requestOrigin,'content-type':'application/json','test-actor':actor},body:JSON.stringify({revision:1,reason:'Correction',values:record.values,scope:recordDraftScope({id:actor},slug),...extra})});
  assert.equal((await call(endpoint,'PUT','other')).status,403);
  assert.equal((await call(endpoint,'PUT','maker',{scope:'wrong'})).status,409);
  assert.equal((await call(endpoint,'PUT','maker',{},'https://foreign.test')).status,403);
  assert.equal((await call(endpoint,'PUT')).status,200);
  assert.equal((await call(endpoint+'/delete','POST')).status,409);
  assert.equal((await call(endpoint+'/delete','POST','maker',{revision:2})).status,200);
});

test('company ERP records can be revised or deleted in Diesel without changing the source',async t=>{
  const directory=await mkdtemp(join(tmpdir(),'diesel-company-edit-'));
  const store=await openItemSubmissions(directory);
  const app=express();
  registerItemSubmissions(app,{store,publicOrigin:'https://diesel.test',getProfile:async()=>({login:'maker'})});
  const server=app.listen(0,'127.0.0.1');
  await once(server,'listening');
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(directory,{recursive:true,force:true});});
  const base='http://127.0.0.1:'+server.address().port;
  const slug='account-master', source=companyRecords(slug)[0];
  const values={...sampleValues(slug),...source.values,'A/C Name':'Corrected company account'};
  const updated=await store.changeCompany({id:'maker'},slug,source,{revision:1,reason:'Correct name',values},false);
  assert.equal(updated.id,source.id);
  assert.equal(updated.revision,2);
  assert.equal(updated.companySourceId,source.id);
  assert.notEqual(source.name,updated.name);
  assert.equal((await store.get({id:'other'},slug,source.id)).canEdit,false);
  assert.equal((await store.get({id:'maker'},slug,source.id)).canEdit,true);
  const page=await (await fetch(base+'/records?master='+slug+'&id='+source.id+'&dialog=1')).text();
  assert.match(page,/Corrected company account/);
  const deletion=await store.changeCompany({id:'maker'},slug,source,{revision:2,reason:'Duplicate account'},true);
  assert.equal(deletion.status,'deleted');
  assert.equal(companyRecords(slug)[0].status,'approved','source data stays intact');
  const list=await (await fetch(base+'/api/master-data/records?master='+slug)).json();
  assert.ok(!list.records.some(record=>record.id===source.id),'deleted source does not reappear');
  const freshSource=companyRecords('storage-location-master')[0];
  await store.changeCompany({id:'maker'},freshSource.master,freshSource,{revision:1,reason:'Remove duplicate'},true);
  const storage=await (await fetch(base+'/api/master-data/records?master=storage-location-master')).json();
  assert.ok(!storage.records.some(record=>record.id===freshSource.id));
});
