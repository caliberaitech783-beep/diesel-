export const round = value => Math.round((value + Number.EPSILON) * 10000) / 10000;
export const money = value => Math.round((value + Number.EPSILON) * 100) / 100;
export function requireValue(test,message) { if (!test) throw Error(message); }
export function validDate(value) {
  return typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value)
    && Number.isFinite(Date.parse(value)) && new Date(value).toISOString().slice(0,10) === value;
}
export function businessDay(now = new Date()) {
  return new Date(now.getTime() + (5.5-review.cutOffHour)*3600000).toISOString().slice(0,10);
}
export function dayBefore(day, days = 1) { return new Date(Date.parse(day)-days*86400000).toISOString().slice(0,10); }
export function validateFields(type,input) {
  const data = {};
  for (const field of type.fields) {
    const raw = input[field.key] ?? field.default;
    if (field.type === 'file') {
      if (raw?.length) data[field.key] = raw;
      else requireValue(field.optional,'Add ' + field.label.toLowerCase() + '.');
      continue;
    }
    const value = typeof raw === 'number' || typeof raw === 'string' ? String(raw).trim() : '';
    if (!value) { requireValue(field.optional,'Enter ' + field.label + '.'); continue; }
    requireValue(value.length <= 2000,field.label + ' is too long.');
    if (field.type === 'number') {
      requireValue(/^-?\d+(\.\d+)?$/.test(value) && Number.isFinite(Number(value)) && Math.abs(Number(value)) <= 1e12,'Enter a valid number for ' + field.label + '.');
      requireValue(field.key === 'temperature' || Number(value) >= 0,field.label + ' cannot be negative.');
      if (field.step===1) requireValue(Number.isSafeInteger(Number(value)),field.label+' must be a whole number.');
      if (field.max!==undefined) requireValue(Number(value)<=field.max,field.label+' must be at most '+field.max+'.');
      data[field.key] = Number(value);
    } else {
      const selected = field.oldOptions?.get(value) ?? value;
      if (field.options) requireValue(field.options.includes(selected),'Choose a listed ' + field.label + '.');
      if (field.type === 'date') requireValue(validDate(value),'Choose a valid date for ' + field.label + '.');
      if (field.type === 'month') requireValue(/^\d{4}-(0[1-9]|1[0-2])$/.test(value),'Choose a valid month.');
      data[field.key] = selected;
    }
  }
  return data;
}

export function evaluate(doc, all, moves, policy = entryPolicy(), siteConfig) {
  const { site, day, id } = doc;
  const records = all.filter(row => row.id !== id && row.site === site && row.day <= day);
  const posted = type => records.filter(row => row.type === type && row.status === 'Posted');
  const reserved = type => all.filter(row => row.site === site && row.id !== id && row.type === type && !['Draft','Returned','Superseded'].includes(row.status));
  function linked(key,type) {
    const found = posted(type).find(row => row.id === doc.data[key]);
    requireValue(found,'Choose a posted ' + type + ' for this site and date.');
    return found;
  }
  const location = code => siteConfig?.storage.find(row=>row.code===code);
  const balance = (storage, atSite = site) => round((siteConfig ? location(storage)?.opening : (storage === review.tank.label ? review.tank.opening : review.bowser.opening))
    + moves.filter(m => m.site === atSite && m.storage === storage && m.day <= day).reduce((a,m)=>a+m.litres,0));
  const sum = (rows,field) => round(rows.reduce((total,row)=>total+Number(row.result[field] ?? 0),0));
  const cost = (throughDay=day) => {
    if (siteConfig) return siteAverageRate(siteConfig,all,site,throughDay);
    const grns = posted('E7').filter(r=>r.day<=throughDay);
    const litres = review.tank.opening + review.bowser.opening;
    return (litres*ratePerKL()+grns.reduce((v,r)=>v+r.result.accepted*r.result.landed,0)) / (litres+sum(grns,'accepted'));
  };
  const ctx = { doc, all, records, posted, reserved, linked, balance, sum, cost, other:otherSite(site), limits: policy.limits, siteConfig };
  const run = purchasing[doc.type] ?? receiving[doc.type] ?? stockEntries[doc.type] ?? accountsAndClose[doc.type];
  requireValue(run,'This entry is generated by Pulse.');
  const result = policy.approvals(doc, run(doc.data,ctx));
  for (const move of result.moves ?? []) {
    const next = round(balance(move.storage,move.site ?? site) + move.litres);
    const maximum = siteConfig ? location(move.storage)?.safe : (move.storage === review.tank.label ? review.tank.safe : review.bowser.capacity);
    requireValue(next >= 0 && next <= maximum,'This movement exceeds available stock or storage capacity at ' + move.storage + '.');
  }
  return result;
}
